pub fn float_luau(v: f32) -> String {
    if v.is_finite() {
        let s = format!("{v:.6}");
        s.trim_end_matches('0').trim_end_matches('.').to_string()
    } else {
        "0".to_string()
    }
}

pub fn render_font_meta_dts(has_outline: bool) -> String {
    let mut out = "// This file is automatically @generated by truffle.\n\
     // DO NOT EDIT MANUALLY.\n\n\
     export interface FontMetaPage {\n\
     \tw: number;\n\
     \th: number;\n\
     }\n\n\
     export interface FontKerningMeta {\n\
     \tleftClass: number[];\n\
     \trightClass: number[];\n\
     \tleftCount: number;\n\
     \trightCount: number;\n\
     \tmatrix: number[];\n\
     }\n\n\
     export interface FontMetaV2 {\n\
     \tlineHeight: number;\n\
     \tbaseline: number;\n\
     \tpx: number;\n\
     \tcharset: string;\n\
     \tpages: FontMetaPage[];\n\
     \tadvances: number[];\n\
     \toffsetX: number[];\n\
     \toffsetY: number[];\n\
     \trects: number[];\n\
     \tkerning: FontKerningMeta;\n\
     }\n\n\
     export interface FontMetaOutlineV2 extends Omit<FontMetaV2, \"kerning\"> {\n\
     \tkerning: FontKerningMeta | undefined;\n\
     }\n\n\
     declare const font: FontMetaV2;\n\
     export { font };\n"
        .to_string();
    if has_outline {
        out.push_str("\ndeclare const outline: FontMetaOutlineV2;\nexport { outline };\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dts_contains_v2_exports() {
        let dts = render_font_meta_dts(false);
        assert!(dts.contains("export interface FontMetaV2"));
        assert!(dts.contains("declare const font: FontMetaV2"));
    }

    #[test]
    fn compact_serialized_meta_stays_small() {
        use super::super::kerning::KerningClasses;

        let charset = "ABC".to_string();
        let glyphs = GlyphLayerMeta {
            advances: vec![10.0, 12.0, 11.0],
            offset_x: vec![0.0; 3],
            offset_y: vec![0.0; 3],
            rects: vec![0, 1, 2, 3, 4, 0, 5, 6, 7, 8, 0, 9, 10, 11, 12],
        };
        let kerning = KerningClasses {
            left_class: vec![0, 1, 2],
            right_class: vec![0, 1, 2],
            left_count: 3,
            right_count: 3,
            matrix: vec![0.0; 9],
        };
        let meta = FontMetaV2 {
            line_height: 95,
            baseline: 11,
            px: 85.0,
            charset,
            pages: vec![AtlasPageMeta { w: 1024, h: 1024 }],
            glyphs,
            kerning,
            outline: None,
        };

        let luau = serialize_font_meta_luau(&meta);
        assert!(luau.contains("lineHeight = 95"));
        assert!(!luau.contains("version"));
        assert!(luau.lines().count() < 200);
    }
}
